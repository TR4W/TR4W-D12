"""Write tr4w/target/dom/urc.dom from the URC DX Territories List.

The URC DX RTTY Contest's exchange is an RST and a 3-letter territory code
from the sponsor's list (docs/ContestRules/URC/rules.md); every code is one
multiplier, counted per band. This script turns the saved list
(docs/ContestRules/URC/territories.md, a Markdown table of
Prefix | Territory | Code) into the .dom TR4W loads:

   CLB = CLB, ^Chelyabinsk Region

-- the code is the key, the multiplier and the only alias, so the multiplier a
QSO earns is the code itself (never a name cut to the table's key width);
the ^ entry is the name the remaining-multiplier window shows.

WHAT logdom.EnumDOMFILE READS, AND WHY THE NAMES ARE CLEANED:
   - a line holding '=' is an ENTRY (there is no comment syntax), so the
     header written here holds none;
   - the right-hand side is split at every ',', so a comma inside a name
     would make the rest of the name an ALIAS of the code -- commas in names
     become ';';
   - names are written as ASCII: other .dom files are ASCII or Latin-1, and
     a BOM-less file is read in the machine's ANSI code page. Accents are
     dropped (Vasterbotten for the sponsor's accented spelling); anything that will not reduce
     to ASCII stops the script rather than writing a '?'.

MMS (maritime mobile) is NOT written: it is not a multiplier, and the
contest's class reads it itself (uContestURCDXRTTY).

The script refuses -- and writes nothing -- on a duplicated code, a code that
is not three letters, or a row it cannot read. It is re-runnable; run it after
the sponsor's list is re-saved:

   python tools/urc/make_urc_dom.py
   python tools/urc/make_urc_dom.py --check     (compare only; exit 1 on a difference)
"""

import argparse
import os
import sys
import unicodedata

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SOURCE = os.path.join(REPO, 'docs', 'ContestRules', 'URC', 'territories.md')
TARGET = os.path.join(REPO, 'tr4w', 'target', 'dom', 'urc.dom')

# Letters NFKD does not decompose into a base letter and a mark.
EXTRA_ASCII = {
   '\u00d8': 'O', '\u00f8': 'o', '\u00c6': 'AE', '\u00e6': 'ae', '\u00df': 'ss',
   '\u0141': 'L', '\u0142': 'l', '\u0110': 'D', '\u0111': 'd', '\u00de': 'Th',
   '\u00fe': 'th', '\u0152': 'OE', '\u0153': 'oe', '\u0131': 'i',
   '\u2019': "'", '\u2018': "'", '\u2013': '-', '\u2014': '-',
}

HEADER = [
   'Entries for the URC DX RTTY Contest -- one per territory of the URC DX Territories List.',
   'Each 3-letter territory code is its own multiplier (counted per band). MMS is not here:',
   'maritime mobile is no multiplier and the contest class reads it.',
   'GENERATED by tools/urc/make_urc_dom.py from docs/ContestRules/URC/territories.md -- do not edit by hand.',
   'No line of this header may hold an equals sign: the reader takes any such line as an entry.',
   'https://unicomradio.com/urc_dx_territories_list.html',
   '',
]


def to_ascii(text, row_number):
   """The name as ASCII, or SystemExit naming the row."""
   out = []
   for ch in text:
      if ch in EXTRA_ASCII:
         out.append(EXTRA_ASCII[ch])
         continue
      for part in unicodedata.normalize('NFKD', ch):
         if unicodedata.combining(part):
            continue
         out.append(part)
   result = ''.join(out)
   if not result.isascii():
      raise SystemExit('row %d: cannot reduce "%s" to ASCII' % (row_number, text))
   return result


def clean_name(name, row_number):
   """The display name EnumDOMFILE can carry: ASCII, no comma, no '='."""
   result = to_ascii(name, row_number).replace(',', ';')
   if '=' in result or '^' in result:
      raise SystemExit('row %d: name "%s" holds a character the .dom reader treats as syntax' % (row_number, name))
   return ' '.join(result.split())


def read_territories(path):
   """[(code, name)] in the list's order, refusing anything doubtful."""
   rows = []
   seen = {}
   with open(path, encoding='utf-8') as source:
      lines = source.read().splitlines()
   in_table = False
   for number, line in enumerate(lines, start=1):
      if not line.startswith('|'):
         in_table = False
         continue
      cells = [cell.strip() for cell in line.strip().strip('|').split('|')]
      if cells == ['Prefix', 'Territory', 'Code']:
         in_table = True
         continue
      if not in_table or set(''.join(cells)) <= set('- '):
         continue
      if len(cells) != 3:
         raise SystemExit('line %d: expected 3 cells, found %d' % (number, len(cells)))
      code = cells[2]
      if len(code) != 3 or not code.isascii() or not code.isalpha() or not code.isupper():
         raise SystemExit('line %d: code "%s" is not three capital letters' % (number, code))
      if code in seen:
         raise SystemExit('line %d: code %s duplicates line %d' % (number, code, seen[code]))
      seen[code] = number
      rows.append((code, clean_name(cells[1], number)))
   if not rows:
      raise SystemExit('no territory rows found in %s' % path)
   return rows


def render(rows):
   lines = list(HEADER)
   for code, name in rows:
      lines.append('%s = %s, ^%s' % (code, code, name))
   return '\r\n'.join(lines) + '\r\n'


def main():
   parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
   parser.add_argument('--check', action='store_true',
                       help='compare with the file on disk and write nothing')
   args = parser.parse_args()

   rows = read_territories(SOURCE)
   text = render(rows)
   data = text.encode('ascii')

   if args.check:
      with open(TARGET, 'rb') as existing:
         same = existing.read() == data
      print('%s: %d territories, %s' % (TARGET, len(rows), 'up to date' if same else 'DIFFERS'))
      return 0 if same else 1

   with open(TARGET, 'wb') as target:
      target.write(data)
   print('wrote %s: %d territories, no duplicate codes' % (TARGET, len(rows)))
   return 0


if __name__ == '__main__':
   sys.exit(main())
