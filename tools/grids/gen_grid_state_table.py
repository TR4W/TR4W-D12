"""Generate the grid -> state table of tr4w/src/uGridLookup.pas.

SOURCE. vuccgrids.dat, the ARRL's VUCC grid list that ships with TrustedQSL
(C:\\Program Files (x86)\\TrustedQSL\\vuccgrids.dat; version 1.6, updated
2026-03-27 when this was written). Its lines look like

   <vucc entity="291" pas="WA" grid="CN88" />

entity is the ADIF DXCC number, pas the primary administrative subdivision
(filled only for 1 Canada, 291 USA, 6 Alaska and 110 Hawaii), grid a four
character Maidenhead square. The file lists EVERY subdivision a grid touches,
edges included.

WHAT IS KEPT. Every grid that has at least one non-empty pas, and for it only
the rows that have a pas. Grids of subdivision-less entities are dropped: they
never name a state.

THE CODES. Canada's two old codes are written the way ADIF's
Primary_Administrative_Subdivision enumeration for DXCC 1 spells them:
NF -> NL, PQ -> QC. Every other code is passed through.

OUTPUT. Two include files, CRLF, next to uGridLookup.pas:

   uGridStateTableCount.inc   GRID_STATE_TABLE_COUNT = <n>;
   uGridStateTable.inc        one entry per line, sorted by grid:
                              'CN88=1:BC;291:WA'  ('<entity>:<state>[,<state>]'
                              blocks separated by ';', entities in the order
                              291, 6, 110, then ascending; states sorted)

The output is deterministic: the same input gives the same bytes.

USAGE (repository root):

   python -I tools/grids/gen_grid_state_table.py <path to vuccgrids.dat>

The version line of the source goes into the first comment of the table
include, so a regeneration shows which file version made it.
"""

import os
import re
import sys

ROW = re.compile(r'<vucc\s+entity="(\d+)"\s+pas="(\w*)"\s+grid="([A-R]{2}\d{2})"\s*/>')
VERSION = re.compile(r'<vuccgrids\s+majorversion="(\d+)"\s+minorversion="(\d+)"'
                     r'\s+updatedate="([\d-]+)"')

ADIF_CODE = {'NF': 'NL', 'PQ': 'QC'}

ENTITY_ORDER = {291: 0, 6: 1, 110: 2}


def entity_key(entity):
   return (ENTITY_ORDER.get(entity, 3), entity)


def main(argv):
   if len(argv) != 2:
      sys.stderr.write(__doc__)
      return 2
   with open(argv[1], 'r', encoding='utf-8') as source:
      text = source.read()

   version = VERSION.search(text)
   if version is None:
      sys.stderr.write('no <vuccgrids ...> version line in the input\n')
      return 1
   versionText = 'vuccgrids.dat version %s.%s, updated %s' % version.groups()

   grids = {}
   rows = 0
   for match in ROW.finditer(text):
      rows += 1
      entity = int(match.group(1))
      pas = ADIF_CODE.get(match.group(2), match.group(2))
      if pas == '':
         continue
      grids.setdefault(match.group(3), {}).setdefault(entity, set()).add(pas)

   if rows == 0 or not grids:
      sys.stderr.write('no rows read: refusing to write an empty table\n')
      return 1

   entries = []
   for grid in sorted(grids):
      blocks = []
      for entity in sorted(grids[grid], key=entity_key):
         blocks.append('%d:%s' % (entity, ','.join(sorted(grids[grid][entity]))))
      entries.append("'%s=%s'" % (grid, ';'.join(blocks)))

   here = os.path.dirname(os.path.abspath(__file__))
   target = os.path.normpath(os.path.join(here, '..', '..', 'tr4w', 'src'))

   lines = ['(* GENERATED by tools/grids/gen_grid_state_table.py from ' + versionText,
            '   (ARRL, as shipped with TrustedQSL). DO NOT EDIT: regenerate. See',
            '   the header of uGridLookup.pas for the licence notice. *)']
   for i, entry in enumerate(entries):
      lines.append(entry + (',' if i < len(entries) - 1 else ''))

   with open(os.path.join(target, 'uGridStateTable.inc'), 'wb') as out:
      out.write(('\r\n'.join(lines) + '\r\n').encode('ascii'))
   with open(os.path.join(target, 'uGridStateTableCount.inc'), 'wb') as out:
      out.write(('GRID_STATE_TABLE_COUNT = %d;\r\n' % len(entries)).encode('ascii'))

   sys.stdout.write('%s: %d rows read, %d grids kept\n' %
                    (versionText, rows, len(entries)))
   return 0


if __name__ == '__main__':
   sys.exit(main(sys.argv))
