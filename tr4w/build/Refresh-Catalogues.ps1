<#
.SYNOPSIS
   Bring every .po catalogue up to date with the program, and report on them.

.DESCRIPTION
   ONE THING THIS CANNOT DO, AND IT IS STEP ONE. The template
   (tr4w\languages\tr4w_laz.pot) is regenerated by the LAZARUS IDE and by
   nothing else -- lazbuild will not do it. Open tr4w\tr4w.lpi, Project Options
   -> i18n, tick "Resave forms with enabled i18n", then Run -> Clean up and
   Build. This script checks whether the template looks older than the forms and
   says so, but it cannot regenerate it.

   WHAT IT DOES DO, for every catalogue in i18n\:

     1. po_merge  -- adds strings that are new since last time.
     2. po_lint   -- checks placeholders, accelerators and edge whitespace.
     3. a summary -- entries, translated, and how many still need review.

   WHY MERGE AND NOT REGENERATE. pas2po.py rebuilds a catalogue from the
   src\lang tables and would overwrite anything edited in Poedit. It is for
   STARTING a language, not refreshing one. po_merge only ever ADDS: it does not
   delete, reword, clear a msgstr, or clear a fuzzy flag. Roughly 417 strings
   per language are finished native-speaker work and are not to be
   re-translated.

.PARAMETER Preview
   Run the merge without writing anything. The lint and the summary still run.

.EXAMPLE
   powershell -ExecutionPolicy Bypass -File tr4w\build\Refresh-Catalogues.ps1
   powershell -ExecutionPolicy Bypass -File tr4w\build\Refresh-Catalogues.ps1 -Preview
#>

param(
   [switch] $Preview
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$repo  = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$i18n  = Join-Path $repo 'i18n'
$pot   = Join-Path $repo 'tr4w\languages\tr4w_laz.pot'
$tools = Join-Path $repo 'tools\i18n'

function Get-Python
   {
   foreach ($c in @('python', 'py'))
      {
      $cmd = Get-Command $c -ErrorAction SilentlyContinue
      if ($cmd) { return $cmd.Source }
      }
   throw 'no python on PATH'
   }

$python = Get-Python

if (-not (Test-Path -LiteralPath $pot))
   {
   Write-Host "Refresh-Catalogues: no template at $pot"
   Write-Host '   It is generated by the Lazarus IDE -- see the notes at the top of this script.'
   exit 2
   }

# The template is generated FROM the forms, so a form newer than it means the
# template is stale and the merge below cannot see those strings.
$formDir = Join-Path $repo 'tr4w\src'
$newest = Get-ChildItem -Path $formDir -Filter '*.lfm' -Recurse |
          Sort-Object LastWriteTime -Descending |
          Select-Object -First 1
$potTime = (Get-Item -LiteralPath $pot).LastWriteTime
if ($newest -and ($newest.LastWriteTime -gt $potTime))
   {
   Write-Host ''
   Write-Host 'Refresh-Catalogues: THE TEMPLATE IS OLDER THAN THE FORMS.'
   Write-Host ("   newest form : {0}  ({1})" -f $newest.LastWriteTime, $newest.Name)
   Write-Host ("   template    : {0}" -f $potTime)
   Write-Host '   Strings added to a form since then are NOT in the template and will not be'
   Write-Host '   merged. Regenerate it in the Lazarus IDE first. Continuing anyway -- the'
   Write-Host '   merge is still safe, just incomplete.'
   Write-Host ''
   }

# ---------------------------------------------------------------- 1. the merge

Write-Host '--- po_merge (adds new strings; never edits an existing translation)'
$mergeArgs = @((Join-Path $tools 'po_merge.py'), '--pot', $pot)
if (-not $Preview)
   {
   $mergeArgs += '--apply'
   }
else
   {
   Write-Host '    PREVIEW -- nothing will be written'
   }
& $python @mergeArgs
if ($LASTEXITCODE -ne 0)
   {
   Write-Host "po_merge failed ($LASTEXITCODE)"
   exit 1
   }

# ----------------------------------------------------------------- 2. the lint

Write-Host ''
Write-Host '--- po_lint'
& $python (Join-Path $tools 'po_lint.py') --all
$lintExit = $LASTEXITCODE

# -------------------------------------------------------------- 3. the summary

Write-Host ''
Write-Host '--- catalogues'
Write-Host ('{0,-8} {1,8} {2,11} {3,11}  {4}' -f 'LANG', 'entries', 'translated', 'to review', '')
Write-Host ('-' * 54)

foreach ($po in (Get-ChildItem -Path $i18n -Filter 'tr4w_*.po' | Sort-Object Name))
   {
   $entries = 0
   $done    = 0
   $fuzzy   = 0
   $inFuzzy = $false
   foreach ($line in (Get-Content -LiteralPath $po.FullName -Encoding UTF8))
      {
      if ($line -match '^#~')            { continue }
      if ($line -match '^#,.*\bfuzzy\b') { $inFuzzy = $true; continue }
      if ($line -match '^msgstr\s+"(.*)"')
         {
         $entries++
         if ($Matches[1].Trim())
            {
            $done++
            # FUZZY ONLY COUNTS WHEN THERE IS SOMETHING TO REVIEW. An entry that
            # is empty AND fuzzy -- which is every entry in a freshly seeded
            # language -- is simply untranslated, and counting it as "needs
            # work" too made approved come out negative.
            if ($inFuzzy) { $fuzzy++ }
            }
         $inFuzzy = $false
         }
      }
   # The header is an entry with an empty msgid; it is not a translatable string.
   if ($entries -gt 0) { $entries-- }

   $ready = $done - $fuzzy      # translated, and reviewed
   $pct = ''
   if ($entries -gt 0) { $pct = '{0,3}% approved' -f [int](100 * $ready / $entries) }
   Write-Host ('{0,-8} {1,8} {2,11} {3,11}  {4}' -f
               ($po.BaseName -replace '^tr4w_', ''), $entries, $done, $fuzzy, $pct)
   }

Write-Host ''
Write-Host 'Only APPROVED entries reach the binary. Anything still "Needs work" in Poedit is'
Write-Host 'dropped by Make-LanguageRes.ps1, so a machine-drafted language adds nothing to the'
Write-Host 'exe until a person has reviewed it.'

exit $lintExit
